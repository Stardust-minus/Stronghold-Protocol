test('audio stems stay extensionless; explicit suffixes match upstream requested-first/fallback resolution', () => {
  const files = AUDIO_EXTS.map((ext) => ({ path: 'assets/audio/bgm/theme' + ext }));
  const routes = mediaMappings(files.reverse(), AUDIO_EXTS, '/media/');
  assert.equal(routes.length, AUDIO_EXTS.length + 1);
  assert.deepEqual(routes.find(({ url }) => url === '/media/bgm/theme'),
    { url: '/media/bgm/theme', requestedExtension: '', file: 'assets/audio/bgm/theme.mp3', ext: '.mp3', mime: 'audio/mpeg' });
  for (const ext of AUDIO_EXTS) assert.equal(routes.find(({ requestedExtension }) => requestedExtension === ext).ext, ext);
  for (const availableExts of [['.mp3', '.ogg'], ['.ogg'], ['.m4a', '.opus'], ['.wav']]) {
    const available = availableExts.map((ext) => ({ path: 'assets/audio/bgm/theme' + ext }));
    for (const route of mediaMappings(available, AUDIO_EXTS, '/media/')) {
      const requested = route.requestedExtension;
      const order = requested ? [requested, ...AUDIO_EXTS.filter((ext) => ext !== requested)] : AUDIO_EXTS;
      const expected = order.find((ext) => availableExts.includes(ext));
      assert.equal(route.file, 'assets/audio/bgm/theme' + expected, route.url);
      assert.equal(route.mime, AUDIO_MIME[expected], route.url);
      if (!requested) assert.doesNotMatch(route.url, /\.(mp3|m4a|aac|ogg|oga|opus|wav)$/);
    }
  }
  assert.throws(() => mediaMappings(files, ['.flac'], '/media/'), /Unexpected shared/);
  assert.throws(() => mediaMappings(files, AUDIO_EXTS, '/new-media/'), /Unexpected shared/);
  assert.throws(() => mediaMappings([{ path: 'assets/audio/theme.MP3' }], AUDIO_EXTS, '/media/'), /Unsupported/);
  assert.throws(() => mediaMappings([{ path: 'assets/audio/theme.mp3.ogg' }], AUDIO_EXTS, '/media/'), /still ends/);
});

