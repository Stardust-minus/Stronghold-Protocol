async function freePort() {
  const server = createServer();
  await new Promise((resolve, reject) => server.listen(0, '127.0.0.1', resolve).once('error', reject));
  const port = server.address().port;
  await new Promise((resolve) => server.close(resolve));
  return port;
}
async function rawGet(port, path) {
  return new Promise((resolve, reject) => {
    const req = request({ host: '127.0.0.1', port, path }, (res) => {
      let body = ''; res.setEncoding('utf8'); res.on('data', (chunk) => { body += chunk; });
      res.on('end', () => resolve({ status: res.statusCode, body, headers: res.headers }));
    });
    req.on('error', reject); req.end();
  });
}

function nginxBinary(t) {
  const nginx = process.env.NGINX_BIN || 'nginx';
  const version = spawnSync(nginx, ['-v'], { encoding: 'utf8' });
  if (version.error?.code === 'ENOENT' && !process.env.NGINX_BIN) { t.skip('Nginx is not installed; set NGINX_BIN to run the real route smoke'); return null; }
  assert.equal(version.status, 0, version.stderr || String(version.error));
  return nginx;
}

async function withNginx(nginx, f, manifest, callback) {
  const includes = nginxIncludes(manifest, { staticRoot: f.output });
  for (const [name, contents] of Object.entries(includes)) await put(join(f.base, name), contents);
  const port = await freePort(); const gamePort = await freePort();
  const config = (await readFile(join(REPO, 'deploy/stardust/static/nginx.conf'), 'utf8'))
    .replace(/^user .*;\n/m, '').replace('worker_processes 10;', 'worker_processes 1;')
    .replace('pid /run/ark-static-nginx.pid;', `pid ${f.base}/nginx.pid;`)
    .replace('error_log /dev/stderr warn;', `error_log ${f.base}/nginx-error.log warn;`)
    .replace('include /etc/nginx/mime.types;', process.env.NGINX_MIME_TYPES ? `include ${process.env.NGINX_MIME_TYPES};` : 'types { image/png png; text/css css; application/javascript js; audio/mpeg mp3; }')
    .replace('http {', `http {\n    client_body_temp_path ${f.base}/body;\n    proxy_temp_path ${f.base}/proxy;\n    fastcgi_temp_path ${f.base}/fastcgi;\n    uwsgi_temp_path ${f.base}/uwsgi;\n    scgi_temp_path ${f.base}/scgi;`)
    .replace('access_log /dev/stdout asset;', 'access_log off;')
    .replace('include /opt/ark-static/generated/cache/*.conf;', `include ${f.base}/static-cache.conf;`)
    .replace('include /opt/ark-static/generated/http/*.conf;', `include ${f.base}/static-files.conf;`)
    .replace('include /opt/ark-static/generated/locations/*.conf;', `include ${f.base}/static-locations.conf;`)
    .replace('listen 3000 ssl http2;', `listen 127.0.0.1:${port};`)
    .replace('root /srv/ark-static;', `root ${f.output};`)
    .replace(/^\s*ssl_[^\n]*\n/gm, '')
    .replace(/\n}\s*$/, `\n    server { listen 127.0.0.1:${gamePort}; include ${f.base}/game-static-locations.conf; location / { return 401; } }\n}\n`);
  const configPath = join(f.base, 'nginx.conf'); await put(configPath, config);
  const syntax = spawnSync(nginx, ['-t', '-e', 'stderr', '-p', f.base + '/', '-c', configPath], { encoding: 'utf8' });
  assert.equal(syntax.status, 0, syntax.stderr);
  assert.doesNotMatch(syntax.stderr, /could not build.*map_hash/, syntax.stderr);
  const child = spawn(nginx, ['-e', 'stderr', '-p', f.base + '/', '-c', configPath, '-g', 'daemon off;'], { stdio: ['ignore', 'ignore', 'pipe'] });
  let stderr = ''; child.stderr.on('data', (data) => { stderr += data; });
  try {
    const origin = `http://127.0.0.1:${port}`;
    let ready = false;
    for (let i = 0; i < 100; i++) {
      if (child.exitCode !== null) throw new Error('Nginx exited before ready: ' + stderr);
      try { ready = (await fetch(origin + '/healthz')).ok; if (ready) break; } catch { /* awaiting local readiness */ }
      await delay(25);
    }
    assert.ok(ready, 'Nginx was not ready: ' + stderr);
    await callback({ origin, port, gamePort });
  } finally {
    child.kill('SIGQUIT');
    if (child.exitCode === null) await Promise.race([new Promise((resolve) => child.once('exit', resolve)), delay(2000)]);
    if (child.exitCode === null) child.kill('SIGKILL');
  }
}

