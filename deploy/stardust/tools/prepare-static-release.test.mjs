test('full prepared release Nginx smoke: all whitelist entries, audio mappings and long hash keys', { timeout: 120000 }, async (t) => {
  if (!process.env.NGINX_RELEASE_DIR) { t.skip('Set NGINX_RELEASE_DIR to an already prepared, worker-readable full release'); return; }
  const nginx = nginxBinary(t); if (!nginx) return;
  const output = resolve(process.env.NGINX_RELEASE_DIR);
  const manifest = await verifyStaticRelease(output);
  const base = await mkdtemp(join(tmpdir(), 'ark-static-full-nginx-'));
  await chmod(base, 0o755); t.after(() => rm(base, { recursive: true, force: true }));
  await withNginx(nginx, { output, base }, manifest, async ({ origin, gamePort }) => {
    const prefix = `/releases/${manifest.release}/`;
    const fetchHead = async (path) => {
      const res = await fetch(origin + prefix + path, { method: 'HEAD', headers: { 'Accept-Encoding': 'identity' } });
      assert.equal(res.status, 200, path); assert.match(res.headers.get('cache-control'), /immutable/, path);
      assert.equal(res.headers.get('access-control-allow-origin'), '*', path);
      return res;
    };
    // Bounded concurrent reads exercise every map key, not merely successful config parsing.
    for (let i = 0; i < manifest.files.length; i += 32) {
      await Promise.all(manifest.files.slice(i, i + 32).map(async ({ path, bytes }) => {
        const res = await fetchHead(path);
        assert.equal(res.headers.get('content-length'), String(bytes), path);
      }));
    }
    for (let i = 0; i < manifest.media.length; i += 32) {
      await Promise.all(manifest.media.slice(i, i + 32).map(async ({ url, mime, file }) => {
        const res = await fetchHead(url.slice(1));
        assert.equal(res.headers.get('content-type'), mime, url);
        assert.equal(res.headers.get('content-length'), String(manifest.files.find((entry) => entry.path === file).bytes), url);
      }));
    }
    const first = manifest.media.find(({ requestedExtension }) => !requestedExtension);
    const url = origin + prefix + first.url.slice(1);
    const range = await fetch(url, { headers: { Range: 'bytes=0-15' } });
    assert.equal(range.status, 206); assert.equal((await range.arrayBuffer()).byteLength, 16);
    const cached = await fetch(url, { headers: { 'If-None-Match': range.headers.get('etag') } });
    assert.equal(cached.status, 304); assert.match(cached.headers.get('cache-control'), /immutable/);
    const redirect = await fetch(`http://127.0.0.1:${gamePort}${first.url}?v=check`, { redirect: 'manual' });
    assert.equal(redirect.status, 302);
    assert.equal(redirect.headers.get('location'), `https://ark-asset.hanabi-ai.cn:25442${prefix}${first.url.slice(1)}?v=check`);
    const error = await fetch(origin + prefix + 'media/not-a-track');
    assert.equal(error.status, 404); assert.equal(error.headers.get('cache-control'), 'no-store');
    const stems = manifest.media.filter(({ requestedExtension }) => !requestedExtension).length;
    t.diagnostic(`Verified ${manifest.files.length} exact static files, ${stems} extensionless audio routes and ${manifest.media.length - stems} explicit-suffix aliases with real Nginx`);
  });
});
