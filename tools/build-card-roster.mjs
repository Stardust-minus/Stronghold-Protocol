#!/usr/bin/env node
// tools/build-card-roster.mjs — writes shared/card-roster.js: every operator a display card can show (feedback #62 / #99):
// the visible chess of 第二期下半 and of the other official versions (shared/versions.js dirs), plus the 自选 operators
// (backups.json diy.operators and ownedPool, the 协防干员 pool), those the art manifest has pictures for. The lobby and
// the server need the list without any version's data, so it ships as a small table of its own.
//
//   node tools/build-card-roster.mjs          rewrite the file
//   node tools/build-card-roster.mjs --check  exit 1 when the file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { VERSIONS } from '../shared/versions.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'shared/card-roster.js');
const json = (file) => JSON.parse(readFileSync(path.join(ROOT, file), 'utf8'));

/** @returns {string} the text of shared/card-roster.js */
export function renderRoster() {
  const art = json('data/assets.json').chars;
  const by = new Map();
  const put = (charId, name, rarity) => {
    if (typeof charId !== 'string' || !art[charId] || typeof name !== 'string' || !name) return;
    const prev = by.get(charId);
    if (!prev) by.set(charId, { charId, name, rarity: Number.isInteger(rarity) ? rarity : 0 });
    else if (!prev.rarity && Number.isInteger(rarity)) prev.rarity = rarity;
  };
  for (const v of VERSIONS) {
    const dir = v.dir ? `data/${v.dir.replace(/\/$/, '')}/` : 'data/';
    const chess = json(`${dir}chess.json`);
    for (const c of Array.isArray(chess) ? chess : Object.values(chess)) if (c && !c.isDiy && c.visible !== false) put(c.charId, c.name, c.rarity);
    const diy = json(`${dir}backups.json`).diy || {};
    for (const [id, op] of Object.entries(diy.operators || {})) put(id, op?.name, op?.rarity);
  }
  const rows = [...by.values()].sort((a, b) => (a.charId < b.charId ? -1 : 1));
  return `// shared/card-roster.js — every operator a display card can show (room.card charId / avatar): the lobby and the server
// know it without any version's data. Generated by tools/build-card-roster.mjs; do not edit.
// i18n-ignore-file: operator names, translated by the game-text overlay (tName).

const ROWS = /** @type {[string, string, number][]} */ ([
${rows.map((r) => `  [${JSON.stringify(r.charId)}, ${JSON.stringify(r.name)}, ${r.rarity}],`).join('\n')}
]);

/** @type {readonly Readonly<{ charId: string, name: string, rarity: number }>[]} */
export const CARD_ROSTER = Object.freeze(ROWS.map(([charId, name, rarity]) => Object.freeze({ charId, name, rarity })));
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderRoster();
  if (process.argv.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) { console.error('shared/card-roster.js is stale: node tools/build-card-roster.mjs'); process.exit(1); }
  } else { writeFileSync(OUT, text); console.log(`shared/card-roster.js: ${text.split('\n').filter((l) => l.startsWith('  [')).length} operators`); }
}
